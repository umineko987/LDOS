const TRANSLATION_FRAGMENTS = TRANSLATION_FRAGMENT_SOURCES
  .map((source) => [source, ENGLISH_TRANSLATIONS.get(source)!] as const)
  .toSorted(([left], [right]) => right.length - left.length);

const HAN_TEXT = /\p{Script=Han}/u;

function normalizeSource(text: string): string {
  return text.trim().replace(/\s+/g, " ");
}

function translateCore(text: string): string {
  const exact = ENGLISH_TRANSLATIONS.get(text);
  if (exact !== undefined) return exact;
  for (const [pattern, translate] of DYNAMIC_UI_TRANSLATIONS) {
    const match = pattern.exec(text);
    if (match) return translate(match[0], ...match.slice(1));
  }
  if (text.includes(" · ")) {
    const parts = text.split(" · ");
    const translatedParts = parts.map((part) => ENGLISH_TRANSLATIONS.get(part) ?? part);
    if (translatedParts.some((part, index) => part !== parts[index])) return translatedParts.join(" · ");
  }

  let translated = text;
  for (const [source, target] of TRANSLATION_FRAGMENTS) {
    if (translated.includes(source)) translated = translated.split(source).join(target);
  }
  return translated
    .replaceAll("，", ", ")
    .replaceAll("；", "; ")
    .replaceAll("。", ".")
    .replaceAll("？", "?")
    .replaceAll("！", "!")
    .replaceAll("、", ", ")
    .replaceAll("（", " (")
    .replaceAll("）", ")")
    .replaceAll("：", ": ")
    .replaceAll("“", "\"")
    .replaceAll("”", "\"")
    .replaceAll("「", "")
    .replaceAll("」", "")
    .replace(/\s+([,.!?;:])/g, "$1")
    .replace(/ {2,}/g, " ");
}

export function translateUiText(text: string, target: UiLanguage): string {
  if (target === "zh" || !HAN_TEXT.test(text)) return text;
  const leading = /^\s*/.exec(text)![0];
  const trailing = /\s*$/.exec(text)![0];
  const core = normalizeSource(text);
  return `${leading}${translateCore(core)}${trailing}`;
}

export function translateCurrentUiText(text: string): string {
  return translateUiText(text, get(language));
}

export function setLanguage(next: UiLanguage): void {
  language.set(next);
}

export function toggleLanguage(current: UiLanguage): void {
  language.set(current === "zh" ? "en" : "zh");
}
