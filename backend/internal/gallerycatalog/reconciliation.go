// ReconcileReviewResult durably records both the old rejected paths and their
// final destinations. Only final destinations remain excluded after a rescan;
// a newly created image at an old path is a fresh candidate.
func (s *Service) ReconcileReviewResult(ctx context.Context, batchID string, retained, excludedOriginal, rejected []string) (Row, error) {
	source, e := s.db.QueryRow(ctx, "SELECT id FROM gallery_sources WHERE batch_id=?", batchID)
	if e != nil {
		return nil, e
	}
	if source == nil {
		return nil, nil
	}
	sid := str(source, "id")
	release, e := s.LockSources(ctx, sid)
	if e != nil {
		return nil, e
	}
	defer release()
	eventID := reconciliationID(sid, batchID)
	for _, paths := range [][]string{retained, excludedOriginal, rejected} {
		for _, rel := range paths {
			if e = ValidateRelativePath(rel, false); e != nil {
				return nil, e
			}
		}
	}
	e = s.db.WriteTransaction(ctx, func(tx *sql.Tx) error {
		_, e := tx.ExecContext(ctx, `INSERT INTO gallery_reconciliation_events(id,source_id,batch_id,status,created_at,updated_at) VALUES(?,?,?,'pending',?,?) ON CONFLICT(source_id,batch_id) DO UPDATE SET status='pending',error_code='',updated_at=excluded.updated_at`, eventID, sid, batchID, now(), now())
		if e != nil {
			return e
		}
		// A pre-existing journal can have an ID generated by an older backend.
		event, e := store.QueryRowTx(ctx, tx, "SELECT id FROM gallery_reconciliation_events WHERE source_id=? AND batch_id=?", sid, batchID)
		if e != nil {
			return e
		}
		eventID = str(event, "id")
		if _, e = tx.ExecContext(ctx, "DELETE FROM gallery_reconciliation_items WHERE event_id=?", eventID); e != nil {
			return e
		}
		rules := map[string]string{}
		for _, p := range retained {
			rules[p] = "kept"
		}
		for _, p := range excludedOriginal {
			rules[p] = "excluded_original"
		}
		for _, p := range rejected {
			rules[p] = "excluded"
		}
		for p, disposition := range rules {
			if _, e = tx.ExecContext(ctx, "INSERT INTO gallery_reconciliation_items(event_id,relative_path,disposition) VALUES(?,?,?)", eventID, p, disposition); e != nil {
				return e
			}
			visibility := "excluded"
			if disposition == "kept" {
				visibility = "kept"
			}
			if _, e = tx.ExecContext(ctx, "UPDATE gallery_assets SET dedup_visibility=?,updated_at=? WHERE source_id=? AND relative_path=?", visibility, now(), sid, p); e != nil {
				return e
			}
			if visibility == "excluded" {
				if _, e = tx.ExecContext(ctx, "DELETE FROM gallery_search_index WHERE source_id=? AND relative_path=?", sid, p); e != nil {
					return e
				}
			}
		}
		if _, e = tx.ExecContext(ctx, "UPDATE gallery_sources SET dedup_state='reconciliation_pending',indexed_version=indexed_version+1,updated_at=? WHERE id=?", now(), sid); e != nil {
			return e
		}
		return refreshCountsTx(ctx, tx, sid)
	})
	if e != nil {
		return nil, e
	}
	if e = s.applyReconciliation(ctx, eventID); e != nil {
		_ = s.exec(context.WithoutCancel(ctx), "UPDATE gallery_reconciliation_events SET status='failed',error_code='review_reconciliation_apply_failed',attempt_count=attempt_count+1,updated_at=? WHERE id=?", now(), eventID)
	}
	return s.GetSource(ctx, sid)
}
func (s *Service) applyReconciliation(ctx context.Context, eventID string) error {
	return s.db.WriteTransaction(ctx, func(tx *sql.Tx) error {
		event, e := store.QueryRowTx(ctx, tx, "SELECT * FROM gallery_reconciliation_events WHERE id=?", eventID)
		if e != nil {
			return e
		}
		if event == nil {
			return failure("reconciliation_not_found", 404)
		}
		if str(event, "status") == "applied" {
			return nil
		}
		sid := str(event, "source_id")
		rules, e := store.QueryRowsTx(ctx, tx, "SELECT * FROM gallery_reconciliation_items WHERE event_id=?", eventID)
		if e != nil {
			return e
		}
		for _, rule := range rules {
			visibility := "excluded"
			if str(rule, "disposition") == "kept" {
				visibility = "kept"
			}
			if _, e = tx.ExecContext(ctx, "UPDATE gallery_assets SET dedup_visibility=?,updated_at=? WHERE source_id=? AND relative_path=?", visibility, now(), sid, rule["relative_path"]); e != nil {
				return e
			}
			if visibility == "excluded" {
				if _, e = tx.ExecContext(ctx, "DELETE FROM gallery_search_index WHERE source_id=? AND relative_path=?", sid, rule["relative_path"]); e != nil {
					return e
				}
			}
		}
		review, e := store.QueryRowTx(ctx, tx, "SELECT status FROM crawl_reviews WHERE batch_id=?", event["batch_id"])
		if e != nil {
			return e
		}
		finished := review == nil || str(review, "status") == "applied" || str(review, "status") == "apply_failed"
		state := "review_pending"
		if finished {
			state = "applied"
		}
		if _, e = tx.ExecContext(ctx, "UPDATE gallery_sources SET dedup_state=?,dedup_applied_version=CASE WHEN ? THEN content_version ELSE dedup_applied_version END,indexed_version=indexed_version+1,updated_at=? WHERE id=?", state, finished, now(), sid); e != nil {
			return e
		}
		if _, e = tx.ExecContext(ctx, "UPDATE gallery_reconciliation_events SET status='applied',attempt_count=attempt_count+1,error_code='',updated_at=?,applied_at=? WHERE id=?", now(), now(), eventID); e != nil {
			return e
		}
		return refreshCountsTx(ctx, tx, sid)
	})
}
func (s *Service) RetryReviewReconciliation(ctx context.Context, sourceID string) (Row, error) {
	release, e := s.LockSources(ctx, sourceID)
	if e != nil {
		return nil, e
	}
	defer release()
	event, e := s.db.QueryRow(ctx, "SELECT id FROM gallery_reconciliation_events WHERE source_id=? AND status IN ('pending','failed')", sourceID)
	if e != nil {
		return nil, e
	}
	if event == nil {
		return nil, failure("reconciliation_not_retryable", 409)
	}
	if e = s.applyReconciliation(ctx, str(event, "id")); e != nil {
		return nil, e
	}
	return s.GetSource(ctx, sourceID)
}
func (s *Service) RecoverReconciliations(ctx context.Context) error {
	events, e := s.db.QueryRows(ctx, "SELECT id,source_id FROM gallery_reconciliation_events WHERE status IN ('pending','failed')")
	if e != nil {
		return e
	}
	for _, event := range events {
		release, e := s.LockSources(ctx, str(event, "source_id"))
		if e != nil {
			return e
		}
		e = s.applyReconciliation(ctx, str(event, "id"))
		release()
		if e != nil {
			return e
		}
	}
	return nil
}
func (s *Service) OnReviewApplied(ctx context.Context, batchID string, excludedAssetIDs []string) (Row, error) {
	source, e := s.db.QueryRow(ctx, "SELECT id FROM gallery_sources WHERE batch_id=?", batchID)
	if e != nil || source == nil {
		return nil, e
	}
	sid := str(source, "id")
	release, e := s.LockSources(ctx, sid)
	if e != nil {
		return nil, e
	}
	defer release()
	excluded := map[string]bool{}
	for _, aid := range excludedAssetIDs {
		excluded[aid] = true
	}
	e = s.db.WriteTransaction(ctx, func(tx *sql.Tx) error {
		assets, e := store.QueryRowsTx(ctx, tx, "SELECT id FROM gallery_assets WHERE source_id=? AND lifecycle_state='active'", sid)
		if e != nil {
			return e
		}
		for _, a := range assets {
			visibility := "kept"
			if excluded[str(a, "id")] {
				visibility = "excluded"
			}
			if _, e = tx.ExecContext(ctx, "UPDATE gallery_assets SET dedup_visibility=?,updated_at=? WHERE id=?", visibility, now(), a["id"]); e != nil {
				return e
			}
			if visibility == "excluded" {
				if _, e = tx.ExecContext(ctx, "DELETE FROM gallery_search_index WHERE asset_id=?", a["id"]); e != nil {
					return e
				}
			}
		}
		if _, e = tx.ExecContext(ctx, "UPDATE gallery_sources SET dedup_state='applied',dedup_applied_version=content_version,indexed_version=indexed_version+1,updated_at=? WHERE id=?", now(), sid); e != nil {
			return e
		}
		return refreshCountsTx(ctx, tx, sid)
	})
	if e != nil {
		return nil, e
	}
	return s.GetSource(ctx, sid)
}
func (s *Service) MarkReviewPending(ctx context.Context, batchID string) error {
	return s.exec(ctx, "UPDATE gallery_sources SET dedup_state='review_pending',updated_at=? WHERE batch_id=? AND dedup_required=1", now(), batchID)
}
